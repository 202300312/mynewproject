"""고등학생을 위한 머신러닝 개념 학습 페이지."""
import streamlit as st
from ui import page_header, info_card
from auth import require_login

require_login()
page_header("LESSON 01 · CONCEPT", "머신러닝이란 무엇일까요?",
            "데이터에서 규칙을 찾아 새로운 상황을 예측하는 컴퓨터의 학습 방법을 알아봅니다.")

st.markdown("## 1. 머신러닝의 정의")
st.markdown("""
**머신러닝(Machine Learning, 기계학습)** 은 컴퓨터가 데이터에서 패턴을 학습하여,
새로운 데이터에 대한 **예측이나 판단**을 수행하게 하는 인공지능(AI)의 한 분야입니다.
모든 판단 규칙을 사람이 일일이 작성하는 대신, **학습 데이터**를 이용해 모델의 규칙을 조정합니다.
""")
st.markdown('<div class="lesson-note">💡 <b>핵심 질문</b> — 컴퓨터가 꽃의 종류를 구별하려면, 꽃의 어떤 정보를 관찰해야 할까요?</div>', unsafe_allow_html=True)

left, right = st.columns(2, gap="large")
with left:
    info_card("🧾 전통적인 프로그래밍", "사람이 작성한 <b>규칙</b> + 데이터 → 결과")
with right:
    info_card("🤖 지도 머신러닝", "<b>데이터 + 정답(레이블)</b>을 활용하여 모델 학습 → 새 데이터의 예측")

st.markdown("## 2. 머신러닝의 주요 학습 방식")
tabs = st.tabs(["🎯 지도학습", "🔎 비지도학습", "🏆 강화학습"])
with tabs[0]:
    st.markdown("""### 지도학습 (Supervised Learning)
입력 데이터와 **정답(레이블)** 을 함께 학습합니다. 정답이 범주라면 **분류**, 연속적인 숫자라면 **회귀** 문제입니다.

- 분류: 이메일이 스팸인지 정상인지 판단하기
- 회귀: 집의 특성을 바탕으로 가격 예측하기
- 이 앱의 **붓꽃 품종 예측**도 지도학습의 분류 문제입니다.
""")
with tabs[1]:
    st.markdown("""### 비지도학습 (Unsupervised Learning)
정답 레이블 없이 데이터에서 **유사한 집단이나 구조**를 찾습니다.

- 군집화: 구매 성향이 비슷한 고객을 묶기
- 차원 축소: 복잡한 데이터를 적은 수의 변수로 요약하기

비지도학습의 결과가 항상 사람에게 의미 있는 범주와 일치하는 것은 아닙니다.
""")
with tabs[2]:
    st.markdown("""### 강화학습 (Reinforcement Learning)
에이전트가 환경에서 **행동 → 보상 → 다음 행동**을 반복하며 누적 보상이 큰 전략을 학습합니다.

- 게임 속에서 점수를 높이는 행동 학습
- 로봇의 이동이나 제어 전략 학습

강화학습은 단순히 정답을 외우는 방식과 다릅니다.
""")

st.markdown("## 3. AI · 머신러닝 · 딥러닝의 관계")
st.markdown("**인공지능(AI) ⊃ 머신러닝(ML) ⊃ 딥러닝(DL)**")
info_card("인공지능", "사람의 지능적 작업을 컴퓨터가 수행하도록 하는 광범위한 기술과 연구 영역")
info_card("머신러닝", "그중에서 데이터에 기반해 모델의 규칙이나 매개변수를 학습하는 방법")
info_card("딥러닝", "머신러닝 중 여러 층의 인공신경망을 활용하는 방법")

st.markdown("## 4. 모델이 만들어지는 과정")
st.markdown("**데이터 수집 → 전처리 → 학습/평가 데이터 분리 → 모델 학습 → 평가 → 새로운 데이터 예측**")
with st.expander("각 단계가 하는 일을 자세히 알아보기", expanded=True):
    st.markdown("""
1. **데이터 수집**: 필요한 특징(입력 변수)과 정답(레이블)을 모읍니다.
2. **전처리**: 누락값과 이상값을 확인하고, 필요하면 값을 변환합니다.
3. **데이터 분리**: 학습에 사용할 데이터와 평가할 데이터를 구분합니다.
4. **모델 학습**: 학습 데이터에서 분류 경계를 찾습니다.
5. **모델 평가**: 학습에 사용하지 않은 데이터에서 성능을 측정합니다.
6. **새로운 예측**: 처음 보는 입력값에 대해 결과를 예측합니다.
""")

st.markdown("## 5. 예측 모델을 이해할 때 주의할 점")
st.info("머신러닝 결과는 반드시 정답인 것이 아닙니다. 데이터의 양과 품질, 편향, 측정 오류, 학습 범위에 따라 성능이 달라집니다.")
st.markdown("""모델이 학습 데이터를 지나치게 외우는 **과적합(Overfitting)** 을 경계해야 하며,
테스트 데이터의 성능을 확인해야 합니다. 예측 결과의 수치가 높더라도 검증 조건을 함께 보아야 합니다.""")

st.markdown("## 6. 학습 확인")
question = st.radio("다음 중 지도학습의 예시는 무엇일까요?",
                    ["정답 없이 비슷한 상품을 묶는다", "품종이 표시된 꽃 데이터로 품종 분류 모델을 학습한다", "게임에서 보상을 통해 이동 전략을 학습한다"],
                    index=None)
if st.button("정답 확인", type="primary"):
    if question is None:
        st.warning("먼저 답을 선택해 주세요.")
    elif question.startswith("품종이"):
        st.success("정답입니다! 입력 특징과 정답 품종을 함께 학습하는 지도학습입니다.")
    else:
        st.error("다시 생각해 보세요. 지도학습은 입력과 정답 레이블이 함께 주어집니다.")
